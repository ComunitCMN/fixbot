"""
Общая подготовка для всех тестов.

Пять тестов импортируют `bot`, а через него `config`, который требует
настоящих ключей. На рабочем компьютере рядом лежит `.env`, и всё
проходило; на чистом сервере файла нет — и тесты падали просто потому,
что оказались в незнакомом месте. Проверять код это никак не помогало.

Поэтому подставляем заглушки. Заодно тесты перестают зависеть от того,
что именно записано в настоящем `.env`: `ENV_FILE=/dev/null` закрывает
дорогу к нему совсем, так что боевые токены в тесты не попадут и база
клиента случайно не пострадает.
"""

import os

_STUBS = {
    # Признак «идут тесты». По нему разворачивание отказывается трогать
    # systemd: однажды прогон на сервере создал там настоящие службы
    # для выдуманных клиентов. Тесты не должны менять живую машину.
    "FIXBOT_TESTING": "1",
    # Пустой файл вместо настоящих настроек — читать нечего.
    "ENV_FILE": "/dev/null",
    # Только латиница: значения уходят в заголовки запросов, а те
    # кириллицу не принимают — падало бы на кодировке, а не по делу.
    "TELEGRAM_TOKEN": "1:test",
    "ANTHROPIC_API_KEY": "sk-ant-test",
    "AMO_SUBDOMAIN": "test",
    "AMO_LONG_TOKEN": "test",
    "OPERATOR_IDS": "1",
    # В памяти: ни один тест не должен трогать базу на диске.
    "DB_PATH": ":memory:",
}

for _name, _value in _STUBS.items():
    os.environ.setdefault(_name, _value)
